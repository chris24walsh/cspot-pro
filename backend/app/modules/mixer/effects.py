def parameter_spec(base, algorithm, value):
    spec = base.copy()
    index = int(base["path"].rsplit("/", 1)[1]) - 1
    labels = COMMON_LABELS.get(algorithm, [])
    spec["label"] = labels[index] if index < len(labels) else f"Parameter {index + 1}"
    spec["unit"] = "normalized"
    if isinstance(value, int):
        spec.update(kind="int", min=0, max=127, unit="enum ID")
        if algorithm == 10 and index in (2, 3, 4):
            options = (
                ["Stereo", "Cross", "Mono"]
                if index == 2
                else ["1/4", "3/8", "1/2", "2/3", "1", "4/3", "3/2", "2", "3"]
            )
            spec.update(options=options, max=len(options) - 1)
        elif algorithm == 6 and index == 4:
            spec.update(options=["Front", "Rear"], max=1, unit="")
        elif algorithm in (6, 7, 11, 12, 16, 18):
            spec.update(options=["Off", "On"], max=1, unit="")
    return spec
